% 实验2 任务1：信号数组赋值与基础运算
clear; clc; close all;      % 清除工作区、命令行，并关闭旧图窗（便于逐图导出）
% 生成时间向量：步长0.01，范围0到1秒
t = 0:0.01:1;               % t包含0到1共101个点
% 生成频率为5Hz的正弦信号
x = sin(2*pi*5*t);          % sin(2*pi*f*t)，f=5Hz
% 幅度缩放：y = 2*x
y = 2 * x;                  % 将信号幅度放大2倍
% 绘制缩放后的波形
figure;                     % 新建图形窗口
plot(t, y, 'b-', 'LineWidth', 1.5);   % 用蓝色实线绘制
title('幅度缩放后的正弦波形 (y=2x)');  % 设置标题
xlabel('时间 (s)');          % x轴标签
ylabel('幅度');              % y轴标签
grid on;                    % 显示网格线
