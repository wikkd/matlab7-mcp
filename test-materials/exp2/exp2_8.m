% 实验2 任务8：矩阵左除法求解方程组
clear; clc; close all;
% 系数矩阵（sym确保精度分数计算）
A = sym([1,  1,   1;
         2, -1,   1;
         1,  2,  -1]);

b = sym([6; 3; 2]);         % 常数向量
% 使用矩阵左除法求解 AX = b  => X = A\b
% 底层采用LU分解等高效算法，效率远高于inv(A)*b
X = A \ b;
% 显示求解结果
disp('矩阵左除法求解结果');
disp(['x = ', char(X(1))]);
disp(['y = ', char(X(2))]);
disp(['z = ', char(X(3))]);
